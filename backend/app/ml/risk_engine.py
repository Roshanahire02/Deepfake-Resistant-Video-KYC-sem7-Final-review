"""
Model F — Fraud Risk Engine.

Combines all upstream signals into a single 0-100 fraud risk score
using a trained classifier (XGBoost if a trained checkpoint exists,
Logistic Regression as the transparent fallback), plus a SHAP
explanation of which features drove the score.

Because no real labeled KYC-fraud dataset is available to a student,
the model is trained on a *synthetic* dataset generated by
`ml/training/generate_synthetic_data.py` + `ml/training/train_risk_model.py`.
This is documented everywhere the model is used: `model_version` always
states whether the loaded model is the synthetic-trained one or the
untrained rule-based fallback, so nobody mistakes the reported
accuracy for real-world fraud-detection performance.

Feature order (must match training):
    document_score, tampering_probability, face_similarity,
    face_quality, liveness_passed, deepfake_probability, replay_probability
"""
from __future__ import annotations

import os
from functools import lru_cache
from typing import Any, Dict, Optional

import numpy as np

from app.core.config import settings

FEATURE_NAMES = [
    "document_authenticity_score",
    "tampering_probability",
    "face_similarity",
    "face_quality",
    "liveness_passed",
    "deepfake_probability",
    "replay_probability",
]

MODEL_PATH_V1 = lambda: os.path.join(settings.MODEL_DIR, "risk_model.joblib")  # noqa: E731
MODEL_PATH_V2 = lambda: os.path.join(settings.MODEL_DIR, "risk_model_v2.joblib")  # noqa: E731
MODEL_PATH = MODEL_PATH_V1  # kept for backward compatibility with older imports


@lru_cache(maxsize=1)
def _load_model():
    """
    Prefers v2 (7 core signals + rPPG, trained with rPPG allowed to be
    missing); falls back to the original v1 (7 signals) if v2 isn't
    present, then to the labeled rule-based fallback. The loaded bundle's
    own `features` list decides what vector is built, so any of the three
    works without code changes.
    """
    import joblib

    for path in (MODEL_PATH_V2(), MODEL_PATH_V1()):
        if os.path.isfile(path):
            bundle = joblib.load(path)
            feats = bundle.get("features", FEATURE_NAMES)
            return bundle["model"], bundle.get("version", "trained_on_synthetic_data_v1"), True, feats
    return None, "rule_based_fallback_untrained", False, FEATURE_NAMES


# Neutral stand-ins used ONLY when a check could not run (disclosed to the user).
NEUTRAL_DEEPFAKE_PROBABILITY = 0.15  # typical benign level in the training distribution
NEUTRAL_FACE_QUALITY = 0.5
REQUIRED_CHECKS = ("face_match", "liveness")


def _rppg_feature(rppg: Optional[Dict[str, Any]]) -> float:
    """rPPG score on the model's 0-100 scale, or NaN ("missing") when there
    is no genuine reading. NaN is handled natively by the trained XGBoost
    model; a made-up neutral value is never substituted."""
    if rppg and rppg.get("status") == "AVAILABLE" and rppg.get("rppg_score") is not None:
        return float(rppg["rppg_score"]) * 100.0
    return float("nan")


def _rule_based_score(features: Dict[str, float]) -> float:
    """
    Transparent fallback used only if no trained model checkpoint is
    present (e.g. immediately after cloning the repo, before running
    ml/training/train_risk_model.py). A simple weighted-sum heuristic —
    clearly a fallback, never presented as a trained ML result.
    """
    doc = 1.0 - (features["document_authenticity_score"] / 100.0)
    tamper = features["tampering_probability"]
    face_mismatch = 1.0 - features["face_similarity"]
    quality_penalty = 1.0 - features["face_quality"]
    liveness_fail = 0.0 if features["liveness_passed"] else 1.0
    deepfake = features["deepfake_probability"]
    replay = features["replay_probability"]

    weights = {
        "doc": 0.15, "tamper": 0.15, "face_mismatch": 0.20, "quality": 0.05,
        "liveness": 0.15, "deepfake": 0.20, "replay": 0.10,
    }
    score01 = (
        weights["doc"] * doc + weights["tamper"] * tamper + weights["face_mismatch"] * face_mismatch
        + weights["quality"] * quality_penalty + weights["liveness"] * liveness_fail
        + weights["deepfake"] * deepfake + weights["replay"] * replay
    )
    return float(np.clip(score01 * 100, 0, 100))


def compute_risk(
    features: Dict[str, float],
    rppg: Optional[Dict[str, Any]] = None,
    unavailable: Optional[Dict[str, str]] = None,
) -> Dict[str, Any]:
    """
    features keys: document_authenticity_score (0-100), tampering_probability (0-1),
    face_similarity (0-1), face_quality (0-1), liveness_passed (bool),
    deepfake_probability (0-1), replay_probability (0-1)

    rppg: optional dict from app.ml.rppg.analyze_rppg(). With the v2 model
    (risk_model_v2.joblib) its `rppg_score` is a trained 8th feature --
    passed as NaN ("missing") unless status is AVAILABLE, so an
    INSUFFICIENT_SIGNAL/UNAVAILABLE reading never influences the score as
    if it were a real value. With only the v1 model present, rPPG is
    explanation-only and the 7-feature vector is unchanged. See
    docs/rppg.md "Risk-engine integration".
    """
    model, version, is_trained, model_features = _load_model()

    # `unavailable` maps a check name ("face_match", "liveness", "deepfake")
    # to why it could not run. Such a value arrives as None; it is replaced
    # by a neutral default so scoring can proceed, but it is DISCLOSED in the
    # explanation, and if a *required* check (face match / liveness) was
    # unavailable the case can never be auto-VERIFIED (see below).
    unavailable = dict(unavailable or {})
    features = dict(features)
    if features.get("deepfake_probability") is None:
        features["deepfake_probability"] = NEUTRAL_DEEPFAKE_PROBABILITY
    if features.get("face_similarity") is None:
        features["face_similarity"] = settings.FACE_MATCH_THRESHOLD
    if features.get("face_quality") is None:
        features["face_quality"] = NEUTRAL_FACE_QUALITY

    feature_vector = np.array(
        [
            features["document_authenticity_score"],
            features["tampering_probability"] * 100,
            features["face_similarity"] * 100,
            features["face_quality"] * 100,
            100.0 if features["liveness_passed"] else 0.0,
            features["deepfake_probability"] * 100,
            features["replay_probability"] * 100,
        ]
    )
    if "rppg_score" in model_features:
        feature_vector = np.append(feature_vector, _rppg_feature(rppg))
    feature_vector = feature_vector.reshape(1, -1)

    contributions: Dict[str, float] = {}

    if is_trained and model is not None:
        # model predicts probability of FRAUD (class 1); score = that probability * 100
        proba = float(model.predict_proba(feature_vector)[0, 1])
        risk_score = round(proba * 100, 2)

        try:
            import shap

            explainer = shap.TreeExplainer(model) if hasattr(model, "get_booster") else shap.LinearExplainer(
                model, feature_vector
            )
            shap_values = explainer.shap_values(feature_vector)
            values = shap_values[1][0] if isinstance(shap_values, list) else shap_values[0]
            contributions = {name: round(float(v), 4) for name, v in zip(model_features, values)}
        except Exception:
            contributions = {}
    else:
        risk_score = round(_rule_based_score(features), 2)
        # simple proportional "contribution" for the fallback so the UI still has something to show
        total = sum(
            [
                100 - features["document_authenticity_score"],
                features["tampering_probability"] * 100,
                (1 - features["face_similarity"]) * 100,
                (1 - features["face_quality"]) * 100,
                0 if features["liveness_passed"] else 100,
                features["deepfake_probability"] * 100,
                features["replay_probability"] * 100,
            ]
        ) or 1.0
        raw = [
            100 - features["document_authenticity_score"],
            features["tampering_probability"] * 100,
            (1 - features["face_similarity"]) * 100,
            (1 - features["face_quality"]) * 100,
            0 if features["liveness_passed"] else 100,
            features["deepfake_probability"] * 100,
            features["replay_probability"] * 100,
        ]
        contributions = {name: round(v / total * risk_score, 4) for name, v in zip(FEATURE_NAMES, raw)}

    risk_level = (
        "LOW" if risk_score <= settings.RISK_LOW_MAX
        else "MEDIUM" if risk_score <= settings.RISK_MEDIUM_MAX
        else "HIGH"
    )
    decision = (
        "VERIFIED" if risk_level == "LOW"
        else "MANUAL_REVIEW" if risk_level == "MEDIUM"
        else "FLAGGED"
    )

    explanation = build_explanation(features, risk_level, decision, rppg=rppg)

    if unavailable:
        names = ", ".join(f"{k.replace('_', ' ')} ({why})" for k, why in unavailable.items())
        explanation += f" Note: these checks could not be evaluated and contributed no evidence: {names}."
        missing_required = [k for k in REQUIRED_CHECKS if k in unavailable]
        if missing_required and decision == "VERIFIED":
            decision = "MANUAL_REVIEW"
            explanation += (
                " Automatic verification was withheld because a required check was unavailable: "
                + ", ".join(k.replace("_", " ") for k in missing_required) + "."
            )

    return {
        "fraud_risk_score": risk_score,
        "risk_level": risk_level,
        "decision": decision,
        "feature_contributions": contributions,
        "explanation_text": explanation,
        "model_version": version,
        "unavailable_signals": unavailable,
    }


def build_explanation(features: Dict[str, float], risk_level: str, decision: str, rppg: Optional[Dict[str, Any]] = None) -> str:
    reasons = []
    if features["document_authenticity_score"] >= 80:
        reasons.append("the document passed authenticity checks")
    else:
        reasons.append("the document authenticity score was low")

    if features["tampering_probability"] >= 0.5:
        reasons.append("possible tampering indicators were found on the document")

    if features["face_similarity"] >= settings.FACE_MATCH_THRESHOLD:
        reasons.append("face similarity exceeded the configured threshold")
    else:
        reasons.append("face similarity was below the configured threshold")

    if features["liveness_passed"]:
        reasons.append("the liveness challenge was completed successfully")
    else:
        reasons.append("the liveness challenge was not completed successfully")

    if features["deepfake_probability"] < 0.3:
        reasons.append("no significant deepfake indicators were detected")
    else:
        reasons.append("deepfake indicators were detected in the video")

    if features["replay_probability"] < 0.3:
        reasons.append("no significant replay-attack indicators were detected")
    else:
        reasons.append("replay-attack indicators were detected")

    # rPPG is a supplementary physiological signal -- mentioned only
    # when a real reading was available (never for
    # UNAVAILABLE/INSUFFICIENT_SIGNAL, since there is nothing genuine
    # to report), and never as a stand-alone deepfake/spoof verdict.
    if rppg and rppg.get("status") == "AVAILABLE":
        if rppg.get("rppg_score", 0) >= 0.5:
            reasons.append(
                f"a physiological pulse signal (rPPG, ~{rppg.get('heart_rate_bpm')} BPM) consistent with a live "
                f"recording was also detected"
            )
        else:
            reasons.append("the rPPG physiological signal was weak, adding some uncertainty")

    verb = "Verification recommended" if decision == "VERIFIED" else (
        "Sent for manual review" if decision == "MANUAL_REVIEW" else "Verification flagged"
    )
    return f"{verb} ({risk_level} risk) because: " + "; ".join(reasons) + "."
